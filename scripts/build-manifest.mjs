// Single source of truth: avatars.json + project.config.json
// Generates: packages/<name>/manifest.js, packages/<name>/assets/{png,webp},
//            llms.txt, site/avatars.json
import { readFileSync, writeFileSync, mkdirSync, existsSync, cpSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));

const cfg = read("project.config.json");
const { avatars } = read("avatars.json");
const pkgDir = join(root, "packages", cfg.name);
const version = read(`packages/${cfg.name}/package.json`).version;

// --- validate ---
const ids = new Set();
const missing = [];
for (const a of avatars) {
  for (const k of ["id", "name", "mood", "role", "age", "presentation", "alt"]) {
    if (!a[k]) throw new Error(`Avatar ${a.id ?? "?"} is missing "${k}"`);
  }
  if (ids.has(a.id)) throw new Error(`Duplicate id ${a.id}`);
  ids.add(a.id);
  for (const [dir, ext] of [["png", "png"], ["webp", "webp"], ["mp4", "mp4"]]) {
    if (!existsSync(join(root, "assets", dir, `${a.id}.${ext}`))) missing.push(`assets/${dir}/${a.id}.${ext}`);
  }
}
if (missing.length) console.warn(`warning: ${missing.length} asset file(s) missing (ok for the skeleton):\n  ${missing.join("\n  ")}`);

// --- package manifest ---
const meta = {
  name: cfg.name,
  version,
  githubRepo: cfg.githubRepo,
  gitTag: cfg.gitTag,
};
writeFileSync(
  join(pkgDir, "manifest.js"),
  `// GENERATED by scripts/build-manifest.mjs. Do not edit.\nexport const meta = ${JSON.stringify(meta, null, 2)};\nexport const avatars = ${JSON.stringify(avatars, null, 2)};\n`
);

// --- bundle WebP (colored + transparent cutout) and the MP4 loops. PNGs are site-download only. ---
const assetsOut = join(pkgDir, "assets");
rmSync(assetsOut, { recursive: true, force: true });
for (const dir of ["webp", "webp-cutout", "mp4"]) {
  const src = join(root, "assets", dir);
  if (existsSync(src)) cpSync(src, join(assetsOut, dir), { recursive: true });
}

// --- ship licenses and README with the package ---
for (const f of ["LICENSE", "ASSETS-LICENSE.md", "README.md"]) {
  if (existsSync(join(root, f))) cpSync(join(root, f), join(pkgDir, f));
}

// --- site data ---
mkdirSync(join(root, "site"), { recursive: true });
writeFileSync(join(root, "site", "avatars.json"), JSON.stringify({ meta, avatars }, null, 2));

// --- llms.txt ---
const npmBase = `https://cdn.jsdelivr.net/npm/${cfg.name}@${version}/assets`;
const lines = [
  `# ${cfg.displayName}`,
  ``,
  `> ${avatars.length} free clay-style avatars for mockups and UIs. PNG, WebP and looping MP4. Install: npm i ${cfg.name}`,
  ``,
  `## How to use`,
  `- Pick an avatar by mood, role, age, presentation or tags from the list below.`,
  `- Image URL (WebP, 512px): ${npmBase}/webp/<id>.webp`,
  `- Transparent background (cutout): ${npmBase}/webp-cutout/<id>.webp, or imageUrl(id, { variant: "cutout" })`,
  `- Looping video URL (MP4, 720px): ${npmBase}/mp4/<id>.mp4`,
  `- PNGs (colored and transparent) are not in the package; they are free to download from ${cfg.siteUrl}`,
  `- In code: import { avatars, imageUrl, videoUrl } from "${cfg.name}"`,
  `- Always include alt text from the "alt" field.`,
  `- License: code MIT, assets see ASSETS-LICENSE.md. Free for commercial use; do not resell the set.`,
  ``,
  `## Avatars (id | name | mood | role | age | presentation | tags)`,
  ...avatars.map((a) => `- ${a.id} | ${a.name} | ${a.mood} | ${a.role} | ${a.age} | ${a.presentation} | ${(a.tags ?? []).join(", ")}`),
  ``,
];
writeFileSync(join(root, "llms.txt"), lines.join("\n"));
console.log(`Built manifest for ${avatars.length} avatars (v${version}).`);

// --- ship llms.txt with the package (the README tells LLM users to read it from there) ---
cpSync(join(root, "llms.txt"), join(pkgDir, "llms.txt"));
